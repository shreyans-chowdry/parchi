import React from 'react';
import { money, unitLabel, type Invoice } from '../engine';
import { CURRENT as SELLER } from './seller';
import { cash, shortDate } from './format';

interface Props {
  invoice: Invoice;
  stamped?: boolean;
  preview?: boolean;
  sheetRef?: React.Ref<HTMLDivElement>;
}

export function InvoiceSheet({ invoice: inv, stamped, preview, sheetRef }: Props) {
  const place = [inv.party.area, inv.party.city, inv.party.country].filter(Boolean).join(', ');
  return (
    <div className="bill" ref={sheetRef} aria-label={`Invoice ${inv.number}`}>
      <div className="bhead">
        <div>
          <h3>Invoice</h3>
          <div style={{ color: 'var(--ink)', fontWeight: 600, marginTop: 6 }}>{SELLER.name}</div>
          <div style={{ color: 'var(--muted)', fontSize: 12 }}>
            {SELLER.tagline}{SELLER.taxId ? ` · Tax ID ${SELLER.taxId}` : ''} {SELLER.sample && <span style={{ color: 'var(--faint)' }}>(sample)</span>}
          </div>
        </div>
        <div className="no">
          {preview ? 'Next invoice' : 'Invoice no.'}
          <b className="num">{inv.number}</b>
          {shortDate(inv.date)}
        </div>
      </div>

      {stamped && (
        <div className="stamp" aria-hidden="true">
          Billed
          <small>{inv.number}</small>
        </div>
      )}

      <div className="parties">
        <div>
          <small>Bill to</small>
          <b>{inv.party.name}</b>
          <div>{place || 'Walk-in'}</div>
          {inv.party.taxId && <div className="num" style={{ fontSize: 11.5, color: 'var(--muted)' }}>Tax ID {inv.party.taxId}</div>}
        </div>
        <div>
          <small>Tax treatment</small>
          <b>{inv.export ? 'Export' : 'Standard'}</b>
          <div style={{ fontSize: 11.5 }}>{inv.export ? 'Cross-border sale, zero-rated' : 'Sales tax at item rates'}</div>
          <div style={{ fontSize: 11.5, color: 'var(--muted)' }}>Due {shortDate(inv.dueDate)} · {inv.currency}</div>
        </div>
      </div>

      <table>
        <thead>
          <tr><th>Item</th><th>Qty</th><th>Rate</th><th>Amount</th><th>Tax</th></tr>
        </thead>
        <tbody>
          {inv.lines.map((l) => (
            <tr key={l.sku}>
              <td>{l.name}{l.hs && <span className="h">HS {l.hs}</span>}</td>
              <td>{l.qty} <span className="h">{unitLabel(l.unit, l.qty)}</span></td>
              <td>{money(l.rate)}</td>
              <td>{money(l.taxable)}</td>
              <td>{l.taxRate}%</td>
            </tr>
          ))}
          {inv.lines.length === 0 && (
            <tr><td colSpan={5} style={{ textAlign: 'center', color: 'var(--muted)', padding: '14px 0' }}>No billable lines yet</td></tr>
          )}
        </tbody>
      </table>

      <div className="totals">
        <div className="muted"><span>Subtotal{inv.lines[0]?.discountPct ? ` (after ${inv.lines[0].discountPct}% trade discount)` : ''}</span><span>{money(inv.taxable)}</span></div>
        {inv.taxSummary.map((t) => (
          <div className="muted" key={t.rate}><span>Tax {t.rate}%{inv.export ? ' (export)' : ''}</span><span>{money(t.tax)}</span></div>
        ))}
        <div className="grand"><small>Total {inv.currency}</small><span className="num">{cash(inv.grandTotal, 2)}</span></div>
      </div>
      <p className="words">{inv.amountInWords}</p>

      <div className="foot">
        <span>For {SELLER.name}</span>
        <span>Authorised signatory</span>
      </div>
      <p className="sample-tag">{SELLER.sample ? 'Demo invoice generated by Parchi with sample data. Not a tax document.' : 'Generated by Parchi.'}</p>
    </div>
  );
}
