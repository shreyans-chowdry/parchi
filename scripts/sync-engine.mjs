// Copies the engine into the Edge Functions' shared folder, adding the explicit
// ".ts" import extensions Deno requires. The browser, tests and server all run the same code.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const src = 'src/engine';
const dst = 'supabase/functions/_shared/engine';
mkdirSync(dst, { recursive: true });
for (const f of readdirSync(src).filter((f) => f.endsWith('.ts'))) {
  const code = readFileSync(`${src}/${f}`, 'utf8').replace(/from '(\.\/[^']+)'/g, (_, p) => `from '${p.endsWith('.ts') ? p : p + '.ts'}'`);
  writeFileSync(`${dst}/${f}`, `// Generated by scripts/sync-engine.mjs from src/engine/${f}. Do not edit here.\n${code}`);
}
console.log('engine synced to', dst);
